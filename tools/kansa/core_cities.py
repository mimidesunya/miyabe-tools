def mandatory_codes(master: dict[str, dict[str, str]]) -> list[str]:
    """包括外部監査が義務付けられている自治体のコード。

    都道府県は台帳の `entity_type` で引き、政令市と中核市は上の表で持つ。
    台帳に無いコードは落とす（市町村合併で消えた市を残さない）。
    """
    codes = [
        code
        for code, row in master.items()
        if str(row.get("entity_type", "")).strip() == "prefecture"
    ]
    codes.extend(code for code in DESIGNATED_CITY_CODES if code in master)
    codes.extend(code for code in CORE_CITY_CODES if code in master)
    return sorted(set(codes))


def mandatory_kind(code: str, master: dict[str, dict[str, str]]) -> str:
    """その自治体が、どの区分で義務付けられているか。任意なら空。"""
    if str(master.get(code, {}).get("entity_type", "")).strip() == "prefecture":
        return "都道府県"
    if code in DESIGNATED_CITY_CODES:
        return "政令市"
    if code in CORE_CITY_CODES:
        return "中核市"
    return ""
