"""索引側パーサの世代。

スクレイプ済みのファイルから索引を作るときの解釈（公布日の読み方、文字化けの
直し方、会議録かどうかの判定）を直しても、その自治体を再索引するまで公開検索は
古いままになる。再スクレイプは 30 日周期なので、直した日から最大 30 日、
本番には古い解釈の文書が残る。群馬県 710 件の空公布日がこの形だった。

この数字を上げると、`sweep_stale_parser_generation` が古い世代の自治体を
見つけて再索引を積む。ダウンロードはやり直さない。保存済みのファイルを
読み直すだけである。

上げるのは**索引の中身が変わる修正のとき**だけにする。上げ忘れても 30 日で
治るが、上げすぎると全自治体の再索引が走る。
"""

